/**
 * Returns the curated questions list for any specific date.
 */
export function getCuratedQuestionsForDate(dateStr: string): Question[] {
  if (dateStr === '2026-08-20') {
    return dailyCA_2026_08_20;
  }
  if (dateStr === '2026-08-19') {
    return dailyCA_2026_08_19;
  }
  // Default to today's edition with updated IDs and timestamps
  return dailyCA_2026_08_20.map((q, idx) => ({
    ...q,
    id: `ca-${dateStr}-${String(idx + 1).padStart(2, '0')}`,
    editionDate: dateStr,
    generatedAt: `${formatDateDisplay(dateStr)}, 06:00 AM IST`,
  }));
}

function formatDateDisplay(dateStr: string): string {
  try {
    const parts = dateStr.split('-');
    if (parts.length === 3) {
      const d = new Date(parseInt(parts[0]), parseInt(parts[1]) - 1, parseInt(parts[2]));
      return d.toLocaleDateString('en-GB', { day: 'numeric', month: 'short', year: 'numeric' });
    }
  } catch {
    // fallback
  }
  return dateStr;
}
